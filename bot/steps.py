BY_KEY = {s.key: s for s in STEPS}
FULL_ROUTE = [s.key for s in STEPS]
FAST_ROUTE = [s.key for s in STEPS if s.fast]


def prompt_for(step, profile):
    """Step prompt plus whatever this profile adds on top of it."""
    hint = (PROFILE_HINTS.get(profile or "online") or {}).get(step.key)
    if not hint:
        return step.prompt
    return f"{step.prompt}\n\nУЧТИ, ЭТО {PROFILE_TITLE.get(profile, '').upper()}:\n{hint}"


def questions_system_for(profile):
    return QUESTIONS_SYSTEM + "\n\n" + PROFILE_SYSTEM.get(profile or "online",
                                                          PROFILE_SYSTEM["online"])


def route(mode):
    return FAST_ROUTE if mode == "fast" else FULL_ROUTE


def step_at(mode, idx):
    r = route(mode)
    return BY_KEY[r[idx]] if 0 <= idx < len(r) else None


def total(mode):
    return len(route(mode))
