class Step:
    def __init__(self, key, num, title, emoji, prompt, fast=False, web=False, tokens=1600,
                 ask=False):
        self.key = key
        self.num = num
        self.title = title
        self.emoji = emoji
        self.prompt = prompt
        self.fast = fast          # part of the short route
        self.web = web            # offers a web-search run
        self.tokens = tokens
        self.ask = ask            # micro-survey before this step

    @property
    def head(self):
        return f"{self.emoji} <b>Шаг {self.num} · {self.title}</b>"


